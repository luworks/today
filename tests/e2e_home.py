      before=(await task(blk['id']))['time']
      await touch(cdp,'touchStart',blk['x'],blk['y']); await pg.wait_for_timeout(330)
      for i in range(1,8): await touch(cdp,'touchMove',blk['x'],blk['y']-i*8); await pg.wait_for_timeout(16)
      await touch(cdp,'touchEnd'); await pg.wait_for_timeout(300)
      print('pane drag',blk['id'],before,'->',(await task(blk['id']))['time'], await pg.evaluate("document.querySelector('#toast-root').textContent"))
      step('chat capture')
      await pg.fill('#ask','Get the proposal to Alex by Friday. Remind me Thursday. Keep the product idea as a note.'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(300)
      await pg.screenshot(path=S+'43_capture.png')
