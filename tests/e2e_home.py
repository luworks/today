      print('after taps',await pg.evaluate("document.querySelector('#cal-pane').offsetHeight"))
      step('pane drag task')
      await pg.evaluate("document.querySelector('#cal-pane .blk.task').scrollIntoView({block:'center'})"); await pg.wait_for_timeout(150)
