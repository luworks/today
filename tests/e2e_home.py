      await touch(cdp,'touchStart',g['x'],g['y'])
      for i in range(1,12): await touch(cdp,'touchMove',g['x'],g['y']-i*20); await pg.wait_for_timeout(16)
      await touch(cdp,'touchEnd'); await pg.wait_for_timeout(400)
      print('split',await pg.evaluate("document.querySelector('#cal-pane').offsetHeight"))
      await pg.screenshot(path=S+'41_peek.png')
      g=await pg.evaluate("(()=>{const r=document.querySelector('[data-split]').getBoundingClientRect();return {x:r.left+r.width/2,y:r.top+11}})()")
      await touch(cdp,'touchStart',g['x'],g['y'])
      for i in range(1,20): await touch(cdp,'touchMove',g['x'],g['y']+i*25); await pg.wait_for_timeout(16)
      await touch(cdp,'touchEnd'); await pg.wait_for_timeout(500)
