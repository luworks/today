      await pg.click('[data-act=drawer]'); await pg.wait_for_timeout(350)
      await pg.click('.drawer [data-act=chat-new]'); await pg.wait_for_timeout(350)
      await pg.click('[data-act=drawer]'); await pg.wait_for_timeout(350)
      print('threads',await pg.evaluate("document.querySelectorAll('.drawer [data-act=chat-open]').length"))
